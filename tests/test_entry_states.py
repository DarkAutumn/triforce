def _row(**update):
    row = {'state': '1_44w_0', 'level': 1, 'room': '0x44', 'in_cave': False, 'name_ok': True,
           'named_room_matches': True, 'entry': 'w', 'entry_matches': True, 'pre_entry': True, 'monsters_min': 3,
           'monsters_max': 3, 'full_count': 3, 'full': True, 'layouts': 4, 'health': 5.0, 'hearts': 5,
           'route_step': 64, 'expected_hearts': 5, 'max_route_hearts': 7, 'boss_entry_ok': True, 'triforce': 1}
    return {**row, **update}


def test_audit_problems_flag_each_defect():
    assert not audit_problems(_row())
    assert audit_problems(_row(named_room_matches=False, pre_entry=False, full=False)) == \
        ['MISNAMED', 'POST-ENTRY', 'SHORT']
    assert not audit_problems(_row(pre_entry=False, full_count=0))          # nothing to spawn: entry doesn't matter
    assert not audit_problems(_row(pre_entry=False, full_count=None))       # room without game.yaml monsters
    assert audit_problems(_row(name_ok=False)) == ['NAME']
    assert audit_problems(_row(entry_matches=False)) == ['ENTRY']
    assert audit_problems(_row(hearts=16, health=16.0)) == ['HEARTS']                     # never a route state
    assert audit_problems(_row(hearts=16, health=16.0, expected_hearts=None)) == ['HEARTS']
    assert audit_problems(_row(hearts=6, health=6.0)) == ['HEARTS']                       # not the route's 5 here
    assert audit_problems(_row(health=0.5)) == ['HP']
    assert audit_problems(_row(route_step=None, expected_hearts=None)) == ['OFFROUTE']
    assert audit_problems(_row(boss_entry_ok=False)) == ['BOSS-ENTRY']
    lines = format_audit([_row(), _row(state='1_45w_0', full=False, monsters_min=1)]).splitlines()
    assert lines[0].split()[:2] == ['1_44w_0', 'L1:44'] and not lines[0].endswith('SHORT')
    assert lines[1].endswith('SHORT') and 'monsters 1-3/3' in lines[1] and 'hearts  5.0/5' in lines[1]


