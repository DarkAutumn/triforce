from .conftest import REPO_STATES_DIR, require_rom

STEP_17 = "run step 17 (python -m triforce.entry_states build)"


def configured_states():
    return sorted({p for name in list_specialists()
                   for p in load_specialist(name).resolve_start_states(str(REPO_STATES_DIR))})


def _route_hearts(entry: dict) -> int:
    """Max hearts after routed progress, including a completed off-route origin room."""
    route_step = entry['route_step']
    if route_step < 0 and 'from_step' in entry:
        route_step = entry['from_step'] + 1
    return BASE_HEARTS + sum(1 for step in route_steps(entry.get('route', DEFAULT_ROUTE))
                             if step.index < route_step and step.specialist.startswith('boss-'))


def walk_north_with_capture(game):
    """From the start room, walks into 0x67; returns the pre-entry snapshot of that room entry."""
    game.load('start', randomize_rng=False)
    game.capture_pre_entry = True
    for _ in range(40):
        change = game.act('MOVE N 16')
        if change.changed_location:
            break
    game.capture_pre_entry = False
    assert game.state.full_location == (0, 0x67, False)
    return game.last_pre_entry


# --- the shipped states (step 17) ---

def test_every_trainable_specialist_has_start_states():
    require_rom()
    missing = [name for name in list_specialists() if load_specialist(name).trainable
               and not load_specialist(name).resolve_start_states(str(REPO_STATES_DIR))]
    if missing:
        pytest.fail(f"missing start states for {', '.join(missing)}: {STEP_17}", pytrace=False)


def test_configured_start_states_are_clean():
    """Every configured state loads into its named room before entry, spawns the full room and carries the route's
    max hearts (manifest)."""
    require_rom()
    paths = configured_states()
    if not paths:
        pytest.fail(f"missing start states: {STEP_17}", pytrace=False)
    with open(REPO_STATES_DIR / MANIFEST, encoding='utf-8') as file:
        manifest = {entry['file']: entry for entry in json.load(file)}
    game, full = native.Game(states_dir=str(REPO_STATES_DIR)), full_monster_counts()
    for path in paths:
        name = os.path.basename(path)
        row = audit_state(game, path, loads=2, full=full)
        assert row['named_room_matches'], f"{name} loads into {row['room']}"
        assert row['pre_entry'] or row['full_count'] == 0, f"{name} was saved after the room's monsters were created"
        assert row['full'], f"{name} spawns {row['monsters_min']} of {row['full_count']} monsters"
        entry = manifest.get(name)
        if entry is not None:
            assert row['hearts'] == _route_hearts(entry), name


# --- tools on the base state ---

def test_start_state_is_the_first_controllable_frame(tmp_path):
    require_rom()
    path = write_start_state(str(tmp_path))
    assert os.path.basename(path) == 'start.state'
    game = native.Game(states_dir=str(tmp_path))
    state = game.load('start', randomize_rng=False, controllable=True)
    assert state.mode == 5 and state.full_location == (0, 0x77, False)
    assert state.max_health == BASE_HEARTS


def test_game_rooms_reads_game_yaml():
    rooms = game_rooms()
    assert rooms[(0, 0x77, True)]['treasure'] == 'wood-sword'
    assert rooms[(1, 0x44, False)]['treasure'] == 'boomerang'
    assert rooms[(0, 0x17, False)]['enemies'] == {'Unknown_31': 1, 'Unknown_32': 2, 'Zora': 1}
    counts = full_monster_counts()
    assert counts[(0, 0x17)] == 3                   # Zoras aren't part of the room's monster list
    assert (0, 0x77) in counts


def test_pre_entry_snapshot_is_written_fresh_and_audits_clean(game, tmp_path):
    pre_entry = walk_north_with_capture(game)
    game.restore(pre_entry)
    assert is_pre_entry(game.read) and pending_room(game.read) == (0, 0x67)
    path = str(tmp_path / '0_67s_9.state')
    write_entry_state(game, pre_entry, path, MapLocation(0, 0x67, False))
    row = audit_state(game, path, loads=3)
    assert row['pre_entry'] and row['named_room_matches'] and row['full']
    assert (row['level'], row['room'], row['hearts']) == (0, '0x67', BASE_HEARTS)
    assert row['monsters_max'] == row['full_count'] > 0


def test_build_path_writes_the_next_room_and_its_manifest_entry(states_dir, tmp_path):
    manifest = build_path('start', [MapLocation(0, 0x67, False)], chain=0, out=str(tmp_path), iterations=200,
                          patience=5, log=lambda _: None, route=DEFAULT_ROUTE, states_dir=str(states_dir))
    assert [e['file'] for e in manifest] == ['0_67s_0.state']
    entry = manifest[0]
    assert entry['entry'] == 'S' and entry['specialist'] == native.specialist_for((0, 0x67))
    step = next(s for s in route_steps() if s.location == MapLocation(0, 0x67, False) and s.entry == 'S')
    assert entry['route_step'] == step.index and not entry['off_route']
    with open(tmp_path / MANIFEST, encoding='utf-8') as file:
        assert json.load(file) == manifest
    row = audit_state(native.Game(states_dir=str(states_dir)), str(tmp_path / '0_67s_0.state'), loads=2)
    assert row['pre_entry'] and row['full'] and row['named_room_matches']


