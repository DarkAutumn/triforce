def test_audit_flags_crafted_copies_and_fails(states_dir, tmp_path, capsys):
    """F024/F057: a wrong entry letter, chain 7, an unparsable name, a boss room's other entry; exit status 1."""
    require_rom()
    for name in ('1_44e_0', '1_44w_7', 'junk'):
        shutil.copy(REPO_STATES_DIR / '1_44w_0.state', tmp_path / f'{name}.state')
    shutil.copy(REPO_STATES_DIR / '2_0es_0.state', tmp_path / '2_0ew_0.state')
