def test_every_trainable_specialist_has_start_states():
    require_rom()
    missing = [name for name in list_specialists() if load_specialist(name).trainable
               and not load_specialist(name).resolve_start_states(str(REPO_STATES_DIR))]
    if missing:
        pytest.fail(f"missing start states for {', '.join(missing)}: {STEP_17}", pytrace=False)


def test_configured_start_states_are_clean():
    """Every configured state passes the audit: named room and entry side, pre-entry, the full room, the route's max
    hearts at full health, a route step."""
    require_rom()
    paths = configured_states()
    if not paths:
        pytest.fail(f"missing start states: {STEP_17}", pytrace=False)
    game, full = native.Game(states_dir=str(REPO_STATES_DIR)), full_monster_counts()
    index = entry_states.RouteIndex()
    problems = {os.path.basename(path): audit_problems(audit_state(game, path, loads=2, full=full, index=index))
                for path in paths}
    assert {name: found for name, found in problems.items() if found} == {}


def test_every_shipped_state_but_start_has_a_manifest_entry():
    """F023/F046: the hearts check and ``path --source`` need each state's route step."""
    with open(REPO_STATES_DIR / MANIFEST, encoding='utf-8') as file:
        manifest = {entry['file'] for entry in json.load(file)}
    shipped = {os.path.basename(p) for p in glob.glob(str(REPO_STATES_DIR / '*.state'))}
    assert shipped - {'start.state'} - manifest == set()
    assert {os.path.basename(p) for p in configured_states()} - {'start.state'} <= manifest


def test_every_start_state_pattern_matches_a_shipped_state():
    """F033: a glob that matches nothing silently trains on fewer states than the yaml says."""
    dead = [(os.path.basename(path), pattern) for path in sorted(glob.glob(str(SPECIALISTS_DIR / '**' / '*.yaml'),
                                                                          recursive=True))
            for pattern in SpecialistConfig.load(path).start_states
            if not SpecialistConfig.load(path).replace(start_states=[pattern])
            .resolve_start_states(str(REPO_STATES_DIR))]
    assert dead == []


def test_build_defaults_to_the_shipped_chains():
    """F007: a plain ``build`` regenerates every chain the states dir holds."""
    shipped = {parse_state_name(state_label(p))[3] for p in glob.glob(str(REPO_STATES_DIR / '*.state'))
               if parse_state_name(state_label(p))}
    chains = build_parser().parse_args(['build']).chains
    assert [int(c) for c in chains.split(',')] == sorted(shipped) == list(CHAINS)


