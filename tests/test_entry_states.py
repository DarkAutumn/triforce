def test_build_and_path_exit_non_zero_naming_the_first_state_not_rebuilt(monkeypatch, states_dir, tmp_path, capsys):
    """F118: a failed on-route crossing is an error, and the staged result only goes live through ``install``."""
    monkeypatch.setattr(entry_states, 'STATES_DIR', states_dir)
    _fake_crossings(monkeypatch, {0x67: 99})
    staged = tmp_path / 'staged'
    assert entry_states.main(['build', '--chains', '0', '--out', str(staged)]) == 1
    out = capsys.readouterr().out
    assert 'FAILED: not rebuilt from 0_67s_0.state' in out
    assert sorted(p.name for p in staged.glob('*.state')) == ['0_77c_0.state', '0_77cave_0.state']
    live = tmp_path / 'live'
    with pytest.raises(RuntimeError, match='failed at 0_67s_0.state'):
        install(str(staged), str(live))
    assert install(str(staged), str(live), partial=True) == ['0_77c_0.state', '0_77cave_0.state']
    with open(live / MANIFEST, encoding='utf-8') as file:
        assert [e['file'] for e in json.load(file)] == ['0_77cave_0.state', '0_77c_0.state']
    assert entry_states.main(['path', '--source', 'start', '--rooms', '0:0x67', '--out', str(tmp_path / 'p')]) == 1


