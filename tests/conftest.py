"""Shared fixtures on the native stack (``triforce._native``).

Gameplay states come from the corpus base movie (``states_dir``: ``start.state`` at the first gameplay frame,
overworld room 0x77).  Named route states (``1_44w_0``, ...) are regenerated by plan step 17; tests that need one
call ``require_state(name)``, which fails (not skips) with the command to build it.
"""

import os
from pathlib import Path

import pytest

from triforce import paths
from triforce.events import LOGS_DIR_ENV
from triforce.model import ModelConfig, ZeldaPolicy
from triforce.observation import observation_space
from triforce.registry import promote, save_checkpoint
from triforce.specialist import list_specialists

ROM_MISSING = "ROM not found: set TRIFORCE_ROM or create roms/zelda.nes"
ALLOW_NO_ROM_ENV = 'TRIFORCE_ALLOW_NO_ROM'     # =1: a missing ROM skips ROM tests instead of failing them
REPO_STATES_DIR = paths.PACKAGE_DIR / 'states'       # where step 17 writes the route states


def rom_path() -> Path:
    """$TRIFORCE_ROM, else <repo>/roms/zelda.nes."""
    return Path(os.environ.get('TRIFORCE_ROM', paths.ROOT / 'roms' / 'zelda.nes'))


def rom_missing_allowed() -> bool:
    """True when ``TRIFORCE_ALLOW_NO_ROM=1``: ROM tests skip instead of failing."""
    return os.environ.get(ALLOW_NO_ROM_ENV) == '1'


def require_rom():
    """Fails the calling test when the ROM isn't available (skips it with ``TRIFORCE_ALLOW_NO_ROM=1``)."""
    if not rom_path().exists():
        message = f"{ROM_MISSING} ({rom_path()}); {ALLOW_NO_ROM_ENV}=1 skips the ROM tests"
        if rom_missing_allowed():
            pytest.skip(message)
        pytest.fail(message, pytrace=False)


def require_state(name: str) -> Path:
    """Path of a route start state regenerated by step 17 (``triforce/states/<name>.state``); fails the test
    with the command that builds it when it doesn't exist yet."""
    require_rom()
    path = REPO_STATES_DIR / (name if name.endswith('.state') else f'{name}.state')
    if not path.exists():
        pytest.fail(f"missing start state {name}: run step 17 (python -m triforce.entry_states build)",
                    pytrace=False)
    return path


@pytest.fixture(autouse=True)
def logs_dir(tmp_path, monkeypatch):
    """Training event logs go under the test's tmp dir, never the repo's logs/."""
    path = tmp_path / 'logs'
    monkeypatch.setenv(LOGS_DIR_ENV, str(path))
    return path


@pytest.fixture(scope='session')
def states_dir(tmp_path_factory):
    """A states dir holding ``start.state`` (the base movie's first gameplay frame); ``TRIFORCE_STATES_DIR``
    points at it for the session.  Pass ``states_dir=`` to native constructors as well: the native module
    resolves its default states dir once per process."""
    require_rom()
    from triforce._native import Game  # pylint: disable=import-outside-toplevel
    directory = tmp_path_factory.mktemp('states')
    game = Game()
    game.play_movie(str(paths.BASE_MOVIE))
    game.save_state_file(str(directory / 'start.state'))
    old = os.environ.get('TRIFORCE_STATES_DIR')
    os.environ['TRIFORCE_STATES_DIR'] = str(directory)
    yield directory
    if old is None:
        os.environ.pop('TRIFORCE_STATES_DIR', None)
    else:
        os.environ['TRIFORCE_STATES_DIR'] = old


@pytest.fixture
def game(states_dir):
    """A fresh native Game per test, with bare state names resolving in ``states_dir``."""
    from triforce._native import Game  # pylint: disable=import-outside-toplevel
    return Game(seed=0, states_dir=str(states_dir))


@pytest.fixture(scope='module')
def models_dir(tmp_path_factory):
    """Every specialist promoted to a small untrained network."""
    root = tmp_path_factory.mktemp('models')
    config = ModelConfig(hidden_dim=32, entity_d_model=32, entity_ff_dim=32, grid_out_dim=32)
    for name in list_specialists():
        network = ZeldaPolicy(observation_space(), config)
        save_checkpoint(name, 'untrained', network, root=root)
        promote(name, 'untrained', root=root)
    return root
