/// Write 256x240 palette indices as a binary PPM.
pub fn write_ppm(path: &Path, pixels: &[u8]) -> Result<()> {
    let mut out = Vec::with_capacity(16 + pixels.len() * 3);
    write!(out, "P6\n256 240\n255\n")?;
    for &p in pixels {
        out.extend_from_slice(&FCEUMM_PALETTE[usize::from(p & 0x3F)]);
    }
    std::fs::write(path, out)?;
    Ok(())
}
